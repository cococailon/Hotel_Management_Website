using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Mvc.ModelBinding;

namespace Hotel_Management_Website.Models.ViewModels.Booking;

public sealed class BookingDirectCreateViewModel
{
    [BindNever]
    public byte BookingType { get; set; } = 1;

    [BindNever]
    public DateTime CheckInDate { get; set; } = DateTime.Today;

    [Required(ErrorMessage = "Vui lòng chọn ngày check out dự kiến.")]
    [DataType(DataType.Date)]
    public DateTime CheckOutDate { get; set; } = DateTime.Today.AddDays(1);

    [BindNever]
    public TimeOnly DefaultCheckInTime { get; set; }

    [BindNever]
    public TimeOnly DefaultCheckOutTime { get; set; }

    [BindNever]
    public DateTime ExpectedCheckInAt { get; set; }

    [BindNever]
    public DateTime ExpectedCheckOutAt { get; set; }

    [Required(ErrorMessage = "Mã đặt phòng không được để trống.")]
    [StringLength(50, ErrorMessage = "Mã đặt phòng không được vượt quá 50 ký tự.")]
    public string BookingCode { get; set; } = string.Empty;

    [StringLength(255, ErrorMessage = "Ghi chú Booking không được vượt quá 255 ký tự.")]
    public string? BookingNote { get; set; }

    [Range(1, int.MaxValue, ErrorMessage = "Tổng người lớn phải lớn hơn 0.")]
    public int TotalAdults { get; set; }

    [Range(0, int.MaxValue, ErrorMessage = "Tổng trẻ em phải lớn hơn hoặc bằng 0.")]
    public int TotalChildren { get; set; }

    [BindNever]
    public Guid? GuestId { get; set; }

    [StringLength(50, ErrorMessage = "Mã khách hàng không được vượt quá 50 ký tự.")]
    public string GuestCode { get; set; } = string.Empty;

    [BindNever]
    public string AutoGeneratedGuestCode { get; init; } = string.Empty;

    [Required(ErrorMessage = "Tên khách hàng là bắt buộc khi tạo trực tiếp tại quầy.")]
    [StringLength(100, ErrorMessage = "Tên khách hàng không được vượt quá 100 ký tự.")]
    public string GuestName { get; set; } = string.Empty;

    [Required(ErrorMessage = "Ngày sinh là bắt buộc khi tạo trực tiếp tại quầy.")]
    [DataType(DataType.Date)]
    public DateTime? GuestDateOfBirth { get; set; }

    [Required(ErrorMessage = "Giới tính là bắt buộc khi tạo trực tiếp tại quầy.")]
    [Range(0, 2, ErrorMessage = "Giới tính khách hàng không hợp lệ.")]
    public byte? GuestSex { get; set; }

    [Required(ErrorMessage = "Địa chỉ là bắt buộc khi tạo trực tiếp tại quầy.")]
    [StringLength(255, ErrorMessage = "Địa chỉ không được vượt quá 255 ký tự.")]
    public string GuestAddress { get; set; } = string.Empty;

    [Required(ErrorMessage = "Số điện thoại là bắt buộc khi tạo trực tiếp tại quầy.")]
    [StringLength(20, ErrorMessage = "Số điện thoại không được vượt quá 20 ký tự.")]
    public string GuestPhoneNumber { get; set; } = string.Empty;

    [EmailAddress(ErrorMessage = "Email không hợp lệ.")]
    public string? GuestEmail { get; set; }

    [Required(ErrorMessage = "Số giấy tờ là bắt buộc khi tạo trực tiếp tại quầy.")]
    [StringLength(50, ErrorMessage = "Số giấy tờ không được vượt quá 50 ký tự.")]
    public string GuestIdentityNumber { get; set; } = string.Empty;

    [Required(ErrorMessage = "Loại giấy tờ là bắt buộc khi tạo trực tiếp tại quầy.")]
    [Range(0, 2, ErrorMessage = "Loại giấy tờ không hợp lệ.")]
    public byte? GuestIdentityType { get; set; }

    [StringLength(255, ErrorMessage = "Ghi chú khách hàng không được vượt quá 255 ký tự.")]
    public string? GuestNote { get; set; }

    [BindNever]
    public decimal Nights { get; init; }

    [BindNever]
    public decimal EstimatedRoomAmount { get; init; }

    [BindNever]
    public decimal DepositAmount { get; init; }

    public byte? PaymentMethod { get; set; }

    [DataType(DataType.DateTime)]
    public DateTime? PaymentDate { get; set; }

    [StringLength(100, ErrorMessage = "Mã giao dịch không được vượt quá 100 ký tự.")]
    public string? ReferenceCode { get; set; }

    public bool DepositConfirmed { get; set; }

    public bool FinalConfirmation { get; set; }

    [BindNever]
    public IReadOnlyList<GuestOptionViewModel> Guests { get; init; } = Array.Empty<GuestOptionViewModel>();

    public List<BookingDirectRoomTypeViewModel> RoomTypes { get; set; } = new();

    public List<BookingDirectRoomAssignmentViewModel> RoomAssignments { get; set; } = new();
}

public sealed class BookingDirectRoomTypeViewModel
{
    public Guid RoomTypeId { get; init; }
    public string RoomTypeCode { get; init; } = string.Empty;
    public string RoomTypeName { get; init; } = string.Empty;
    public int MaxAdults { get; init; }
    public int MaxChildren { get; init; }
    public decimal PricePerNight { get; init; }
    public decimal DepositPercent { get; init; }
    public int AvailableRoomCount { get; init; }
    public List<CheckInRoomOptionViewModel> AvailableRooms { get; init; } = new();
    public int Quantity { get; set; }
}

public sealed class BookingDirectRoomAssignmentViewModel
{
    public Guid RoomTypeId { get; set; }

    [BindNever]
    public string RoomTypeCode { get; set; } = string.Empty;

    [BindNever]
    public string RoomTypeName { get; set; } = string.Empty;

    [BindNever]
    public int MaxAdults { get; set; }

    [BindNever]
    public int MaxChildren { get; set; }

    public Guid? RoomId { get; set; }

    [Range(0, int.MaxValue, ErrorMessage = "Số người lớn trong phòng phải từ 0 trở lên.")]
    public int Adults { get; set; }

    [Range(0, int.MaxValue, ErrorMessage = "Số trẻ em trong phòng phải từ 0 trở lên.")]
    public int Children { get; set; }

    [StringLength(255, ErrorMessage = "Ghi chú BookingRoom không được vượt quá 255 ký tự.")]
    public string? Note { get; set; }

    [BindNever]
    public IReadOnlyList<CheckInRoomOptionViewModel> AvailableRooms { get; set; } = Array.Empty<CheckInRoomOptionViewModel>();
}

public sealed class BookingDirectCreateResult
{
    public bool Succeeded { get; init; }
    public Guid BookingId { get; init; }
    public string? ErrorMessage { get; init; }
    public IReadOnlyDictionary<string, string> FieldErrors { get; init; } =
        new Dictionary<string, string>();
    public BookingDirectCreateViewModel Model { get; init; } = new();
}
